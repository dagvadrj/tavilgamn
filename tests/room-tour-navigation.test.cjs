const {test}=require('node:test');
const assert=require('node:assert/strict');
const React=require('react');
const THREE=require('three');
const {loadSource}=require('./helpers/load-source.cjs');
const nodes=t=>!t||typeof t!=='object'?[]:[t,...React.Children.toArray(t.props?.children).flatMap(nodes)];
test('Street View arrows click once or drop once, without moving the camera during dragging',()=>{
  const slots=[];let cursor=0;
  const react={useRef:v=>slots[cursor++]??(slots[cursor-1]={current:v}),useState:v=>{const at=cursor++;if(!(at in slots))slots[at]=v;return[slots[at],v=>slots[at]=v];}};
  const {TourArrow}=loadSource('src/three/RoomTourNavigation.tsx',{react,'react-dom':{createPortal:(node)=>node}});
  const camera=new THREE.PerspectiveCamera(60,1,.03,100);
  camera.position.set(0,1.6,2);camera.lookAt(0,0,0);camera.updateMatrixWorld();
  const canvas={ownerDocument:{body:{}},getBoundingClientRect:()=>({left:0,top:0,width:400,height:400})};
  const jumps=[];const point={x:1,z:1};
  const props={camera,canvas,point,onJump:p=>{jumps.push(p);return true;}};
  const render=(patch={})=>{cursor=0;return nodes(TourArrow({...props,...patch}));};
  let tree=render(),button=tree.find(n=>n.type==='button');
  const element={style:{},setPointerCapture(){},hasPointerCapture:()=>true,releasePointerCapture(){}};
  const event={button:0,pointerId:1,clientX:100,clientY:300,currentTarget:element,preventDefault(){},stopPropagation(){}};
  const position=camera.position.toArray();
  button.props.onPointerDown(event);button.props.onPointerUp(event);button.props.onClick({detail:1});
  assert.deepEqual(jumps,[point]);
  button.props.onPointerDown(event);button.props.onPointerMove({...event,clientX:200,clientY:200});
  assert.equal(jumps.length,1);assert.deepEqual(camera.position.toArray(),position);assert.ok(render().some(n=>n.props?.['aria-hidden']==='true' && n.props.style.left===200));
  button.props.onPointerUp({...event,clientX:200,clientY:200});button.props.onClick({detail:1});
  assert.equal(jumps.length,2);assert.ok(Math.abs(jumps[1].x)<1e-6&&Math.abs(jumps[1].z)<1e-6);assert.equal(render().some(n=>n.props?.['aria-hidden']==='true'),false);
  button.props.onPointerDown(event);button.props.onPointerMove({...event,clientX:200});button.props.onPointerCancel(event);button.props.onLostPointerCapture(event);
  assert.equal(jumps.length,2);
  button.props.onClick({detail:0});assert.equal(jumps.length,3);
  tree=render({onJump:()=>false});button=tree.find(n=>n.type==='button');
  button.props.onPointerDown(event);button.props.onPointerUp(event);
  assert.ok(render().some(n=>n.props?.role==='status'));
  tree=render({point:undefined});button=tree.find(n=>n.type==='button');
  button.props.onPointerDown(event);button.props.onPointerUp(event);assert.equal(jumps.length,3);
  button.props.onPointerDown(event);button.props.onPointerMove({...event,clientX:200,clientY:200});button.props.onPointerUp({...event,clientX:200,clientY:200});
  assert.equal(jumps.length,4);
});
